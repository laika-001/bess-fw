#!/usr/bin/env python3
"""Write ml/anomaly_model.h (firmware weights) from ml/model.json.

  python3 ml/export_model.py [model.json] [anomaly_model.h]

train_autoencoder.py runs this automatically. Rebuild and flash the firmware
afterwards (bessflash) to put the new model on the MAX32630.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def lit(x):
    s = f"{float(x):.9g}"
    if not any(c in s for c in ".eEn"):   # "1" -> "1.0": C++ needs a dot before the f suffix
        s += ".0"
    return s + "f"


def fl(xs):
    return ", ".join(lit(x) for x in xs)


def export(src, dst):
    m = json.load(open(src))
    layers = m["layers"]
    W = [w for L in layers for row in L["W"] for w in row]
    B = [b for L in layers for b in L["b"]]
    n_in = len(m["features"])
    lines = [
        "// GENERATED by ml/export_model.py from ml/model.json. Do not edit; retrain instead.",
        f"// Model created {m['created']}, trained on {m['trained_on']['hours']} h of healthy data",
        f"// ({m['trained_on']['from']} to {m['trained_on']['to']}).",
        "#pragma once",
        "namespace anomaly_model {",
        f'static const char CREATED[] = "{m["created"]}";',
        f"static const float TRAINED_HOURS = {m['trained_on']['hours']}f;",
        f"static const int N_IN = {n_in};",
        f"static const int N_LAYERS = {len(layers)};",
        f"static const int LAYER_IN[] = {{{', '.join(str(len(L['W'][0])) for L in layers)}}};",
        f"static const int LAYER_OUT[] = {{{', '.join(str(len(L['W'])) for L in layers)}}};",
        f"static const bool LAYER_TANH[] = {{{', '.join('true' if L['act'] == 'tanh' else 'false' for L in layers)}}};",
        "// features: " + ", ".join(m["features"]),
        f"static const float MEAN[] = {{{fl(m['mean'])}}};",
        f"static const float STD[] = {{{fl(m['std'])}}};",
        f"static const float WEIGHTS[] = {{{fl(W)}}};  // per layer, row-major [out][in]",
        f"static const float BIAS[] = {{{fl(B)}}};",
        f"static const double THRESHOLD = {m['threshold']!r};",
        f"static const int PERSIST_FRAMES = {m.get('persist_frames', 5)};",
        "}  // namespace anomaly_model",
        "",
    ]
    with open(dst, "w") as fh:
        fh.write("\n".join(lines))
    return dst


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "model.json")
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "anomaly_model.h")
    print("wrote", export(src, dst))
